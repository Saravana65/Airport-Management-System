BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE TICKETS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE BOOKINGS CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

-- Commercial Booking Orders (PNR)
CREATE TABLE BOOKINGS (
    BOOKING_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BOOKING_REFERENCE   VARCHAR2(10)    NOT NULL, -- 6-character PNR code
    USER_ID             NUMBER          NOT NULL,
    BOOKING_DATE        TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    TOTAL_AMOUNT        NUMBER(10,2)    NOT NULL,
    STATUS              VARCHAR2(20)    DEFAULT 'CONFIRMED' NOT NULL,
    CREATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_bookings PRIMARY KEY (BOOKING_ID),

    -- Unique Constraint on PNR Booking Reference
    CONSTRAINT uq_booking_ref UNIQUE (BOOKING_REFERENCE),

    -- Foreign Key referencing USERS
    CONSTRAINT fk_bookings_user FOREIGN KEY (USER_ID)
        REFERENCES USERS (USER_ID) ON DELETE CASCADE,

    -- Check Constraints
    CONSTRAINT chk_booking_status CHECK (STATUS IN ('CONFIRMED', 'CANCELLED', 'REFUNDED')),
    CONSTRAINT chk_booking_amount CHECK (TOTAL_AMOUNT >= 0)
);

-- Individual Seat Tickets
CREATE TABLE TICKETS (
    TICKET_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BOOKING_ID          NUMBER          NOT NULL,
    FLIGHT_INSTANCE_ID  NUMBER          NOT NULL,
    PASSENGER_ID        NUMBER          NOT NULL,
    TICKET_NUMBER       VARCHAR2(20)    NOT NULL,
    SEAT_NUMBER         VARCHAR2(5),
    CABIN_CLASS         VARCHAR2(20)    NOT NULL,
    PRICE               NUMBER(10,2)    NOT NULL,
    STATUS              VARCHAR2(20)    DEFAULT 'ISSUED' NOT NULL,
    CREATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_tickets PRIMARY KEY (TICKET_ID),

    -- Unique Constraint on standard 13-digit e-ticket number
    CONSTRAINT uq_ticket_number UNIQUE (TICKET_NUMBER),

    -- Unique Constraint: Prevent duplicate seat allocations on the same flight instance
    -- (In Oracle, rows with NULL seat numbers are ignored, allowing unassigned seats)
    CONSTRAINT uq_flight_seat UNIQUE (FLIGHT_INSTANCE_ID, SEAT_NUMBER),

    -- Foreign Keys
    CONSTRAINT fk_tickets_booking FOREIGN KEY (BOOKING_ID)
        REFERENCES BOOKINGS (BOOKING_ID) ON DELETE CASCADE,
    CONSTRAINT fk_tickets_instance FOREIGN KEY (FLIGHT_INSTANCE_ID)
        REFERENCES FLIGHT_INSTANCES (FLIGHT_INSTANCE_ID) ON DELETE CASCADE,
    CONSTRAINT fk_tickets_passenger FOREIGN KEY (PASSENGER_ID)
        REFERENCES PASSENGERS (PASSENGER_ID) ON DELETE CASCADE,

    -- Check Constraints
    CONSTRAINT chk_ticket_class CHECK (CABIN_CLASS IN ('ECONOMY', 'BUSINESS', 'FIRST')),
    CONSTRAINT chk_ticket_status CHECK (STATUS IN ('ISSUED', 'CHECKED_IN', 'BOARDED', 'CANCELLED')),
    CONSTRAINT chk_ticket_price CHECK (PRICE > 0)
);

CREATE INDEX idx_tickets_booking ON TICKETS (BOOKING_ID);
CREATE INDEX idx_tickets_instance ON TICKETS (FLIGHT_INSTANCE_ID);
CREATE INDEX idx_tickets_passenger ON TICKETS (PASSENGER_ID);

COMMENT ON TABLE BOOKINGS IS 'Passenger reservation records grouped under a unique PNR code.';
COMMENT ON TABLE TICKETS IS 'Individual flight tickets with seat assignments and cabin class fares.';

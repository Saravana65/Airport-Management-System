-- SCRIPT: 11_aade_tables.sql
-- MODULE: Autonomous Airport Data Engine (AADE) Schema
-- DESCRIPTION: Creates relational tables for autonomous monitoring, events,
--              alerts, recommendations, human approvals, and audit trails.
-- AUTHOR: Saravana (BTech Student Capstone Project)
-- ============================================================================

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE AADE_AUDIT_LOGS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE AADE_APPROVAL_REQUESTS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE AADE_RECOMMENDATIONS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE AADE_ALERTS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE AADE_EVENTS CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

-- 1. Autonomous Engine Event Stream
CREATE TABLE AADE_EVENTS (
    EVENT_ID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EVENT_TYPE              VARCHAR2(50)    NOT NULL,
    SEVERITY                VARCHAR2(20)    DEFAULT 'INFO' NOT NULL,
    DESCRIPTION             VARCHAR2(500)   NOT NULL,
    ENTITY_TYPE             VARCHAR2(50),
    ENTITY_ID               VARCHAR2(50),
    STATUS                  VARCHAR2(20)    DEFAULT 'LOGGED' NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_aade_events PRIMARY KEY (EVENT_ID),
    CONSTRAINT chk_aade_event_severity CHECK (SEVERITY IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT chk_aade_event_status CHECK (STATUS IN ('LOGGED', 'PROCESSED', 'ARCHIVED'))
);

-- 2. Active Alert Registry (with Deduplication Hash Key)
CREATE TABLE AADE_ALERTS (
    ALERT_ID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    HASH_KEY                VARCHAR2(64)    NOT NULL,
    ALERT_TYPE              VARCHAR2(50)    NOT NULL,
    SEVERITY                VARCHAR2(20)    DEFAULT 'WARNING' NOT NULL,
    TITLE                   VARCHAR2(150)   NOT NULL,
    MESSAGE                 VARCHAR2(1000)  NOT NULL,
    ENTITY_TYPE             VARCHAR2(50),
    ENTITY_ID               VARCHAR2(50),
    STATUS                  VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    OCCURRENCE_COUNT        NUMBER          DEFAULT 1 NOT NULL,
    FIRST_DETECTED_AT       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_DETECTED_AT        TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    RESOLVED_AT             TIMESTAMP,
    RESOLVED_BY_USER_ID     NUMBER,

    CONSTRAINT pk_aade_alerts PRIMARY KEY (ALERT_ID),
    CONSTRAINT uq_aade_alert_hash UNIQUE (HASH_KEY),
    CONSTRAINT fk_aade_alert_user FOREIGN KEY (RESOLVED_BY_USER_ID)
        REFERENCES USERS (USER_ID) ON DELETE SET NULL,
    CONSTRAINT chk_aade_alert_severity CHECK (SEVERITY IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT chk_aade_alert_status CHECK (STATUS IN ('ACTIVE', 'ACKNOWLEDGED', 'RESOLVED', 'DISMISSED'))
);

-- 3. Rule-Based Recommendations
CREATE TABLE AADE_RECOMMENDATIONS (
    RECOMMENDATION_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ALERT_ID                NUMBER,
    CATEGORY                VARCHAR2(50)    NOT NULL,
    TITLE                   VARCHAR2(150)   NOT NULL,
    DETECTED_ISSUE          VARCHAR2(1000)  NOT NULL,
    RATIONALE               VARCHAR2(1000)  NOT NULL,
    SUGGESTED_ACTION        VARCHAR2(500)   NOT NULL,
    ACTION_TYPE             VARCHAR2(50)    NOT NULL,
    ACTION_PAYLOAD          VARCHAR2(4000),
    STATUS                  VARCHAR2(20)    DEFAULT 'PENDING' NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_aade_recommendations PRIMARY KEY (RECOMMENDATION_ID),
    CONSTRAINT fk_aade_rec_alert FOREIGN KEY (ALERT_ID)
        REFERENCES AADE_ALERTS (ALERT_ID) ON DELETE SET NULL,
    CONSTRAINT chk_aade_rec_status CHECK (
        STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'EXECUTED', 'CANCELLED')
    )
);

-- 4. Human-In-The-Loop Approval Requests
CREATE TABLE AADE_APPROVAL_REQUESTS (
    APPROVAL_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RECOMMENDATION_ID       NUMBER          NOT NULL,
    ACTION_TYPE             VARCHAR2(50)    NOT NULL,
    TITLE                   VARCHAR2(150)   NOT NULL,
    DESCRIPTION             VARCHAR2(500)   NOT NULL,
    ACTION_PAYLOAD          VARCHAR2(4000)  NOT NULL,
    DECISION                VARCHAR2(20)    DEFAULT 'PENDING' NOT NULL,
    DECISION_BY_USER_ID     NUMBER,
    DECISION_REMARKS        VARCHAR2(500),
    REQUESTED_AT            TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    DECIDED_AT              TIMESTAMP,

    CONSTRAINT pk_aade_approvals PRIMARY KEY (APPROVAL_ID),
    CONSTRAINT fk_aade_appr_rec FOREIGN KEY (RECOMMENDATION_ID)
        REFERENCES AADE_RECOMMENDATIONS (RECOMMENDATION_ID) ON DELETE CASCADE,
    CONSTRAINT fk_aade_appr_user FOREIGN KEY (DECISION_BY_USER_ID)
        REFERENCES USERS (USER_ID) ON DELETE SET NULL,
    CONSTRAINT chk_aade_appr_decision CHECK (
        DECISION IN ('PENDING', 'APPROVED', 'REJECTED')
    )
);

-- 5. Immutable Execution Audit Logs
CREATE TABLE AADE_AUDIT_LOGS (
    AUDIT_ID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    APPROVAL_ID             NUMBER,
    ACTION_TYPE             VARCHAR2(50)    NOT NULL,
    EXECUTED_BY_USER_ID     NUMBER,
    EXECUTED_BY_EMAIL       VARCHAR2(100),
    BEFORE_STATE            VARCHAR2(4000),
    AFTER_STATE             VARCHAR2(4000),
    EXECUTION_STATUS        VARCHAR2(20)    DEFAULT 'SUCCESS' NOT NULL,
    DETAILS                 VARCHAR2(1000)  NOT NULL,
    EXECUTED_AT             TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_aade_audit PRIMARY KEY (AUDIT_ID),
    CONSTRAINT fk_aade_audit_appr FOREIGN KEY (APPROVAL_ID)
        REFERENCES AADE_APPROVAL_REQUESTS (APPROVAL_ID) ON DELETE SET NULL,
    CONSTRAINT fk_aade_audit_user FOREIGN KEY (EXECUTED_BY_USER_ID)
        REFERENCES USERS (USER_ID) ON DELETE SET NULL,
    CONSTRAINT chk_aade_audit_status CHECK (EXECUTION_STATUS IN ('SUCCESS', 'FAILED'))
);

-- Performance Indexes
CREATE INDEX idx_aade_events_type ON AADE_EVENTS (EVENT_TYPE, CREATED_AT);
CREATE INDEX idx_aade_alerts_status ON AADE_ALERTS (STATUS, SEVERITY);
CREATE INDEX idx_aade_recs_status ON AADE_RECOMMENDATIONS (STATUS);
CREATE INDEX idx_aade_appr_status ON AADE_APPROVAL_REQUESTS (DECISION, REQUESTED_AT);
CREATE INDEX idx_aade_audit_time ON AADE_AUDIT_LOGS (EXECUTED_AT);

COMMENT ON TABLE AADE_EVENTS IS 'Chronological event stream emitted by autonomous monitors.';
COMMENT ON TABLE AADE_ALERTS IS 'Deduplicated operational alert registry tracking open anomalies.';
COMMENT ON TABLE AADE_RECOMMENDATIONS IS 'Rule-based corrective recommendations generated by AADE.';
COMMENT ON TABLE AADE_APPROVAL_REQUESTS IS 'Human-in-the-loop validation queue requiring operator approval.';
COMMENT ON TABLE AADE_AUDIT_LOGS IS 'Immutable audit records tracking all executed autonomous corrections with before/after state diffs.';

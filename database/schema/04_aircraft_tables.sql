BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE AIRCRAFT CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

CREATE TABLE AIRCRAFT (
    AIRCRAFT_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REGISTRATION_NO     VARCHAR2(20)    NOT NULL,
    MODEL               VARCHAR2(50)    NOT NULL,
    AIRLINE_CODE        VARCHAR2(3)     NOT NULL,
    TOTAL_SEATS         NUMBER          NOT NULL,
    ECONOMY_SEATS       NUMBER          DEFAULT 0 NOT NULL,
    BUSINESS_SEATS      NUMBER          DEFAULT 0 NOT NULL,
    FIRST_SEATS         NUMBER          DEFAULT 0 NOT NULL,
    STATUS              VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_aircraft PRIMARY KEY (AIRCRAFT_ID),

    -- Unique Constraint: International tail registration number (e.g., 'VT-EXG', 'N789AA')
    CONSTRAINT uq_aircraft_reg UNIQUE (REGISTRATION_NO),

    -- Foreign Key referencing AIRLINES
    CONSTRAINT fk_aircraft_airline FOREIGN KEY (AIRLINE_CODE)
        REFERENCES AIRLINES (AIRLINE_CODE) ON DELETE CASCADE,

    -- Check Constraints
    CONSTRAINT chk_aircraft_status CHECK (STATUS IN ('ACTIVE', 'MAINTENANCE', 'RETIRED')),
    CONSTRAINT chk_seats_positive CHECK (TOTAL_SEATS > 0 AND ECONOMY_SEATS >= 0 AND BUSINESS_SEATS >= 0 AND FIRST_SEATS >= 0),
    CONSTRAINT chk_seat_sum CHECK (TOTAL_SEATS = (ECONOMY_SEATS + BUSINESS_SEATS + FIRST_SEATS))
);

CREATE INDEX idx_aircraft_airline ON AIRCRAFT (AIRLINE_CODE);

COMMENT ON TABLE AIRCRAFT IS 'Fleet records including tail numbers, aircraft models, and cabin seat breakdowns.';
COMMENT ON COLUMN AIRCRAFT.REGISTRATION_NO IS 'Unique aircraft tail registration code.';
COMMENT ON COLUMN AIRCRAFT.TOTAL_SEATS IS 'Total certified seating capacity (must equal sum of all classes).';

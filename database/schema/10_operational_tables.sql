BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE OPERATIONAL_LOGS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE NOTIFICATIONS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE FLIGHT_STATUS_HISTORY CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

-- Flight Status Change Audit Log
CREATE TABLE FLIGHT_STATUS_HISTORY (
    HISTORY_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FLIGHT_INSTANCE_ID      NUMBER          NOT NULL,
    OLD_STATUS              VARCHAR2(20),
    NEW_STATUS              VARCHAR2(20)    NOT NULL,
    REASON                  VARCHAR2(255),
    CHANGED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CHANGED_BY_USER_ID      NUMBER,

    -- Primary Key
    CONSTRAINT pk_status_history PRIMARY KEY (HISTORY_ID),

    -- Foreign Keys
    CONSTRAINT fk_history_instance FOREIGN KEY (FLIGHT_INSTANCE_ID)
        REFERENCES FLIGHT_INSTANCES (FLIGHT_INSTANCE_ID) ON DELETE CASCADE,
    CONSTRAINT fk_history_user FOREIGN KEY (CHANGED_BY_USER_ID)
        REFERENCES USERS (USER_ID) ON DELETE SET NULL
);

-- Passenger & Staff Notifications
CREATE TABLE NOTIFICATIONS (
    NOTIFICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID         NUMBER          NOT NULL,
    TITLE           VARCHAR2(100)   NOT NULL,
    MESSAGE         VARCHAR2(500)   NOT NULL,
    NOTIFICATION_TYPE VARCHAR2(30)  DEFAULT 'SYSTEM' NOT NULL,
    IS_READ         CHAR(1)         DEFAULT 'N' NOT NULL,
    CREATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_notifications PRIMARY KEY (NOTIFICATION_ID),

    -- Foreign Key referencing USERS
    CONSTRAINT fk_notifications_user FOREIGN KEY (USER_ID)
        REFERENCES USERS (USER_ID) ON DELETE CASCADE,

    -- Check Constraints
    CONSTRAINT chk_notification_type CHECK (
        NOTIFICATION_TYPE IN ('FLIGHT_DELAY', 'GATE_CHANGE', 'BOARDING', 'CHECKIN_REMINDER', 'SYSTEM')
    ),
    CONSTRAINT chk_notification_read CHECK (IS_READ IN ('Y', 'N'))
);

-- Autonomous Airport Data Engine Activity & Audit Logs
CREATE TABLE OPERATIONAL_LOGS (
    LOG_ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EVENT_CATEGORY          VARCHAR2(50)    NOT NULL,
    SEVERITY                VARCHAR2(20)    DEFAULT 'INFO' NOT NULL,
    DETAILS                 VARCHAR2(1000)  NOT NULL,
    ACTION_TAKEN            VARCHAR2(500),
    REQUIRES_ADMIN_APPROVAL CHAR(1)         DEFAULT 'N' NOT NULL,
    APPROVAL_STATUS         VARCHAR2(20)    DEFAULT 'NOT_REQUIRED' NOT NULL,
    LOGGED_AT               TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_operational_logs PRIMARY KEY (LOG_ID),

    -- Check Constraints
    CONSTRAINT chk_log_severity CHECK (SEVERITY IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT chk_log_approval_flag CHECK (REQUIRES_ADMIN_APPROVAL IN ('Y', 'N')),
    CONSTRAINT chk_log_approval_status CHECK (
        APPROVAL_STATUS IN ('NOT_REQUIRED', 'PENDING', 'APPROVED', 'REJECTED')
    )
);

CREATE INDEX idx_history_instance ON FLIGHT_STATUS_HISTORY (FLIGHT_INSTANCE_ID);
CREATE INDEX idx_notifications_user ON NOTIFICATIONS (USER_ID, IS_READ);
CREATE INDEX idx_oplogs_category ON OPERATIONAL_LOGS (EVENT_CATEGORY, LOGGED_AT);

COMMENT ON TABLE FLIGHT_STATUS_HISTORY IS 'Chronological audit trail tracking flight timetable transitions and delays.';
COMMENT ON TABLE NOTIFICATIONS IS 'Personalized flight alerts and system messages delivered to users.';
COMMENT ON TABLE OPERATIONAL_LOGS IS 'Core foundation table for the Autonomous Airport Data Engine tracking automated events and approvals.';

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE FLIGHT_INSTANCES CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE FLIGHTS CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

-- Master Flight Routes (Template / Timetable)
CREATE TABLE FLIGHTS (
    FLIGHT_NUMBER               VARCHAR2(10)    NOT NULL,
    AIRLINE_CODE                VARCHAR2(3)     NOT NULL,
    ORIGIN_AIRPORT              VARCHAR2(3)     NOT NULL,
    DEST_AIRPORT                VARCHAR2(3)     NOT NULL,
    SCHEDULED_DEPARTURE_TIME    VARCHAR2(5)     NOT NULL, -- Format 'HH24:MI' e.g. '08:30'
    SCHEDULED_ARRIVAL_TIME      VARCHAR2(5)     NOT NULL, -- Format 'HH24:MI' e.g. '11:45'
    FLIGHT_TYPE                 VARCHAR2(20)    DEFAULT 'DIRECT' NOT NULL,
    BASE_FARE                   NUMBER(10,2)    DEFAULT 5000.00 NOT NULL,
    IS_ACTIVE                   CHAR(1)         DEFAULT 'Y' NOT NULL,
    CREATED_AT                  TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key: Flight route designator (e.g., 'AI2014', 'BA1689')
    CONSTRAINT pk_flights PRIMARY KEY (FLIGHT_NUMBER),

    -- Foreign Keys
    CONSTRAINT fk_flights_airline FOREIGN KEY (AIRLINE_CODE)
        REFERENCES AIRLINES (AIRLINE_CODE) ON DELETE CASCADE,
    CONSTRAINT fk_flights_origin FOREIGN KEY (ORIGIN_AIRPORT)
        REFERENCES AIRPORTS (AIRPORT_CODE) ON DELETE CASCADE,
    CONSTRAINT fk_flights_dest FOREIGN KEY (DEST_AIRPORT)
        REFERENCES AIRPORTS (AIRPORT_CODE) ON DELETE CASCADE,

    -- Check Constraints
    CONSTRAINT chk_flight_diff_airports CHECK (ORIGIN_AIRPORT != DEST_AIRPORT),
    CONSTRAINT chk_flight_type CHECK (FLIGHT_TYPE IN ('DIRECT', 'NON-STOP', 'CONNECTING')),
    CONSTRAINT chk_flights_active CHECK (IS_ACTIVE IN ('Y', 'N')),
    CONSTRAINT chk_base_fare_positive CHECK (BASE_FARE > 0)
);

-- Daily Flight Instances (Actual flights on specific calendar dates)
CREATE TABLE FLIGHT_INSTANCES (
    FLIGHT_INSTANCE_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FLIGHT_NUMBER           VARCHAR2(10)    NOT NULL,
    FLIGHT_DATE             DATE            NOT NULL,
    AIRCRAFT_ID             NUMBER,
    DEPARTURE_GATE_ID       NUMBER,
    ARRIVAL_GATE_ID         NUMBER,
    SCHEDULED_DEPARTURE     TIMESTAMP       NOT NULL,
    ACTUAL_DEPARTURE        TIMESTAMP,
    SCHEDULED_ARRIVAL       TIMESTAMP       NOT NULL,
    ACTUAL_ARRIVAL          TIMESTAMP,
    STATUS                  VARCHAR2(20)    DEFAULT 'SCHEDULED' NOT NULL,
    REMARKS                 VARCHAR2(255),
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_flight_instances PRIMARY KEY (FLIGHT_INSTANCE_ID),

    -- Foreign Keys
    CONSTRAINT fk_instance_flight FOREIGN KEY (FLIGHT_NUMBER)
        REFERENCES FLIGHTS (FLIGHT_NUMBER) ON DELETE CASCADE,
    CONSTRAINT fk_instance_aircraft FOREIGN KEY (AIRCRAFT_ID)
        REFERENCES AIRCRAFT (AIRCRAFT_ID) ON DELETE SET NULL,
    CONSTRAINT fk_instance_dep_gate FOREIGN KEY (DEPARTURE_GATE_ID)
        REFERENCES GATES (GATE_ID) ON DELETE SET NULL,
    CONSTRAINT fk_instance_arr_gate FOREIGN KEY (ARRIVAL_GATE_ID)
        REFERENCES GATES (GATE_ID) ON DELETE SET NULL,

    -- Unique Constraint: A flight number can operate at most once on a specific calendar date
    CONSTRAINT uq_flight_date UNIQUE (FLIGHT_NUMBER, FLIGHT_DATE),

    -- Check Constraints
    CONSTRAINT chk_instance_status CHECK (
        STATUS IN ('SCHEDULED', 'BOARDING', 'DEPARTED', 'ON_TIME', 'DELAYED', 'CANCELLED', 'ARRIVED')
    ),
    CONSTRAINT chk_instance_times CHECK (SCHEDULED_ARRIVAL >= SCHEDULED_DEPARTURE)
);

-- Indexes for fast timetable searching
CREATE INDEX idx_flights_route ON FLIGHTS (ORIGIN_AIRPORT, DEST_AIRPORT);
CREATE INDEX idx_instances_date ON FLIGHT_INSTANCES (FLIGHT_DATE, STATUS);
CREATE INDEX idx_instances_depgate ON FLIGHT_INSTANCES (DEPARTURE_GATE_ID);

COMMENT ON TABLE FLIGHTS IS 'Recurring flight schedule templates with route metadata and base fares.';
COMMENT ON TABLE FLIGHT_INSTANCES IS 'Daily physical flight occurrences tracked with real-time operational status and gate assignments.';

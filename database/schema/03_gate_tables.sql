BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE GATES CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

CREATE TABLE GATES (
    GATE_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    AIRPORT_CODE    VARCHAR2(3)     NOT NULL,
    TERMINAL        VARCHAR2(10)    NOT NULL,
    GATE_NUMBER     VARCHAR2(10)    NOT NULL,
    STATUS          VARCHAR2(20)    DEFAULT 'AVAILABLE' NOT NULL,
    IS_ACTIVE       CHAR(1)         DEFAULT 'Y' NOT NULL,
    CREATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_gates PRIMARY KEY (GATE_ID),

    -- Foreign Key referencing AIRPORTS
    CONSTRAINT fk_gates_airport FOREIGN KEY (AIRPORT_CODE)
        REFERENCES AIRPORTS (AIRPORT_CODE) ON DELETE CASCADE,

    -- Unique Constraint: A gate number must be unique within a given terminal and airport
    CONSTRAINT uq_gate_location UNIQUE (AIRPORT_CODE, TERMINAL, GATE_NUMBER),

    -- Check Constraint for valid gate operational status
    CONSTRAINT chk_gate_status CHECK (STATUS IN ('AVAILABLE', 'OCCUPIED', 'MAINTENANCE')),

    CONSTRAINT chk_gates_active CHECK (IS_ACTIVE IN ('Y', 'N'))
);

-- Index on AIRPORT_CODE for fast gate lookups by airport
CREATE INDEX idx_gates_airport ON GATES (AIRPORT_CODE);

COMMENT ON TABLE GATES IS 'Stores terminal gate facilities across airports for aircraft docking and boarding.';
COMMENT ON COLUMN GATES.STATUS IS 'Operational availability: AVAILABLE, OCCUPIED, or MAINTENANCE.';

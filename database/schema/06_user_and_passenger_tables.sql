BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE PASSENGERS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE USERS CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

-- System Users & Role-Based Access Control (RBAC)
CREATE TABLE USERS (
    USER_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EMAIL           VARCHAR2(100)   NOT NULL,
    PASSWORD_HASH   VARCHAR2(255)   NOT NULL,
    ROLE            VARCHAR2(20)    NOT NULL,
    IS_ACTIVE       CHAR(1)         DEFAULT 'Y' NOT NULL,
    CREATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_users PRIMARY KEY (USER_ID),

    -- Unique Constraint on login email
    CONSTRAINT uq_user_email UNIQUE (EMAIL),

    -- Check Constraints
    CONSTRAINT chk_user_role CHECK (ROLE IN ('ADMIN', 'AIRLINE_STAFF', 'AIRPORT_STAFF', 'PASSENGER')),
    CONSTRAINT chk_user_active CHECK (IS_ACTIVE IN ('Y', 'N'))
);

-- Passenger Profiles
CREATE TABLE PASSENGERS (
    PASSENGER_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID         NUMBER,
    FIRST_NAME      VARCHAR2(50)    NOT NULL,
    LAST_NAME       VARCHAR2(50)    NOT NULL,
    PASSPORT_NUMBER VARCHAR2(20)    NOT NULL,
    PHONE           VARCHAR2(20),
    EMAIL           VARCHAR2(100),
    DATE_OF_BIRTH   DATE,
    GENDER          VARCHAR2(1),
    CREATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_passengers PRIMARY KEY (PASSENGER_ID),

    -- Unique Constraint on passport number
    CONSTRAINT uq_passenger_passport UNIQUE (PASSPORT_NUMBER),

    -- Foreign Key referencing USERS (optional for guest bookings)
    CONSTRAINT fk_passengers_user FOREIGN KEY (USER_ID)
        REFERENCES USERS (USER_ID) ON DELETE SET NULL,

    -- Check Constraint on gender
    CONSTRAINT chk_passenger_gender CHECK (GENDER IN ('M', 'F', 'O'))
);

CREATE INDEX idx_passengers_passport ON PASSENGERS (PASSPORT_NUMBER);
CREATE INDEX idx_passengers_user ON PASSENGERS (USER_ID);

COMMENT ON TABLE USERS IS 'Authentication credentials and security roles for all system actors.';
COMMENT ON TABLE PASSENGERS IS 'Traveler demographic records verified via unique passport numbers.';

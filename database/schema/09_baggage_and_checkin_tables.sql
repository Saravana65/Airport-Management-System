BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE BAGGAGE CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE CHECK_IN CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

-- Passenger Check-In & Boarding Passes
CREATE TABLE CHECK_IN (
    CHECK_IN_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TICKET_ID           NUMBER          NOT NULL,
    CHECK_IN_TIME       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    BOARDING_PASS_CODE  VARCHAR2(50)    NOT NULL,
    BOARDING_TIME       TIMESTAMP,
    GATE_ID             NUMBER,
    STATUS              VARCHAR2(20)    DEFAULT 'COMPLETED' NOT NULL,
    CREATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_checkin PRIMARY KEY (CHECK_IN_ID),

    -- Unique Constraint: One boarding pass per ticket
    CONSTRAINT uq_checkin_ticket UNIQUE (TICKET_ID),
    CONSTRAINT uq_boarding_pass UNIQUE (BOARDING_PASS_CODE),

    -- Foreign Keys
    CONSTRAINT fk_checkin_ticket FOREIGN KEY (TICKET_ID)
        REFERENCES TICKETS (TICKET_ID) ON DELETE CASCADE,
    CONSTRAINT fk_checkin_gate FOREIGN KEY (GATE_ID)
        REFERENCES GATES (GATE_ID) ON DELETE SET NULL,

    -- Check Constraints
    CONSTRAINT chk_checkin_status CHECK (STATUS IN ('COMPLETED', 'BOARDED'))
);

-- Checked Luggage & Carousel Allocation
CREATE TABLE BAGGAGE (
    BAGGAGE_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TICKET_ID           NUMBER          NOT NULL,
    TAG_NUMBER          VARCHAR2(30)    NOT NULL,
    WEIGHT_KG           NUMBER(5,2)     NOT NULL,
    STATUS              VARCHAR2(30)    DEFAULT 'CHECKED_IN' NOT NULL,
    CAROUSEL_NUMBER     VARCHAR2(10),
    CREATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_baggage PRIMARY KEY (BAGGAGE_ID),

    -- Unique Constraint on Barcode Bag Tag
    CONSTRAINT uq_baggage_tag UNIQUE (TAG_NUMBER),

    -- Foreign Key referencing TICKETS
    CONSTRAINT fk_baggage_ticket FOREIGN KEY (TICKET_ID)
        REFERENCES TICKETS (TICKET_ID) ON DELETE CASCADE,

    -- Check Constraints
    CONSTRAINT chk_baggage_weight CHECK (WEIGHT_KG >= 0.0 AND WEIGHT_KG <= 60.0),
    CONSTRAINT chk_baggage_status CHECK (
        STATUS IN ('CHECKED_IN', 'SECURITY_CLEARED', 'LOADED', 'TRANSIT', 'CLAIM_READY', 'COLLECTED')
    )
);

CREATE INDEX idx_baggage_ticket ON BAGGAGE (TICKET_ID);
CREATE INDEX idx_checkin_gate ON CHECK_IN (GATE_ID);

COMMENT ON TABLE CHECK_IN IS 'Passenger airport or web check-in records and issued boarding passes.';
COMMENT ON TABLE BAGGAGE IS 'Checked baggage items tracked from ticket intake to baggage reclaim carousels.';

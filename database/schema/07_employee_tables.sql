BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE EMPLOYEES CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

CREATE TABLE EMPLOYEES (
    EMPLOYEE_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID         NUMBER          NOT NULL,
    AIRPORT_CODE    VARCHAR2(3)     NOT NULL,
    AIRLINE_CODE    VARCHAR2(3),    -- NULL for general airport authority / air traffic controllers
    FIRST_NAME      VARCHAR2(50)    NOT NULL,
    LAST_NAME       VARCHAR2(50)    NOT NULL,
    JOB_TITLE       VARCHAR2(50)    NOT NULL,
    SHIFT           VARCHAR2(20)    DEFAULT 'DAY' NOT NULL,
    CONTACT_PHONE   VARCHAR2(20),
    IS_ACTIVE       CHAR(1)         DEFAULT 'Y' NOT NULL,
    CREATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

    -- Primary Key
    CONSTRAINT pk_employees PRIMARY KEY (EMPLOYEE_ID),

    -- Foreign Keys
    CONSTRAINT fk_emp_user FOREIGN KEY (USER_ID)
        REFERENCES USERS (USER_ID) ON DELETE CASCADE,
    CONSTRAINT fk_emp_airport FOREIGN KEY (AIRPORT_CODE)
        REFERENCES AIRPORTS (AIRPORT_CODE) ON DELETE CASCADE,
    CONSTRAINT fk_emp_airline FOREIGN KEY (AIRLINE_CODE)
        REFERENCES AIRLINES (AIRLINE_CODE) ON DELETE SET NULL,

    -- Check Constraints
    CONSTRAINT chk_emp_shift CHECK (SHIFT IN ('DAY', 'NIGHT')),
    CONSTRAINT chk_emp_active CHECK (IS_ACTIVE IN ('Y', 'N'))
);

CREATE INDEX idx_emp_airport ON EMPLOYEES (AIRPORT_CODE);
CREATE INDEX idx_emp_airline ON EMPLOYEES (AIRLINE_CODE);

COMMENT ON TABLE EMPLOYEES IS 'Airport and airline staff records, duty assignments, and shifts.';
